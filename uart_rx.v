//=============================================================================
//  uart_rx.v  ——  串口接收（9600-8N1，LSB first）
//
//  这份代码就是那张清单表的“翻译结果”。每个 always 块开头都标了它对应表里哪一行。
//
//  和发送端最大的区别只有两个：
//    1. 它自己不知道什么时候开始 —— 靠线上的下降沿
//    2. 它要在“每一位的正中间”采样 —— 所以比较值是半位，不是整位
//=============================================================================
module uart_rx #(
    parameter CLOCK_FREQ = 50_000_000,   // 板子时钟 50 MHz
    parameter BAUD       = 9600          // 波特率
)(
    input               Clk,
    input               Rst_n,
    input               uart_rx,         // 从板子引脚进来，和 Clk 没有任何关系
    output reg  [7:0]   Data,            // 收完的字节
    output reg          Rx_Done          // 单拍脉冲：这一字节收完了
);

    //------------------------------------------------------------------
    // 三个数，先算出来
    //   MCNT_BAUD = 5207 : 一位 = 5208 拍，从 0 数到 5207
    //   HALF_BAUD = 2603 : 半位。采样点就定义在 baud_cnt == 2603 那一拍
    //   BW        = 13   : 装得下 5207 需要的位数
    //------------------------------------------------------------------
    localparam MCNT_BAUD = CLOCK_FREQ / BAUD - 1;   // 5207
    localparam HALF_BAUD = MCNT_BAUD / 2;           // 2603
    localparam BW        = $clog2(MCNT_BAUD + 1);   // 13

    //------------------------------------------------------------------
    // 表第 1、2 行：同步链（把“外来的线”搬到“我的时钟域”里）
    //   引脚 -> d0 -> d1 -> d2
    //   d1 是“稳定的当前值”，d2 是它的上一拍（专门用来比边沿）
    //------------------------------------------------------------------
    reg uart_rx_d0, uart_rx_d1, uart_rx_d2;

    always @(posedge Clk or negedge Rst_n) begin
        if (!Rst_n) begin
            uart_rx_d0 <= 1'b1;   // 空闲是高，复位成 1 更接近真实状态
            uart_rx_d1 <= 1'b1;
            uart_rx_d2 <= 1'b1;
        end
        else begin
            uart_rx_d0 <= uart_rx;
            uart_rx_d1 <= uart_rx_d0;
            uart_rx_d2 <= uart_rx_d1;
        end
    end

    // 下降沿 = 上一拍是 1，这一拍是 0
    wire rx_nedge = uart_rx_d2 & ~uart_rx_d1;

    //------------------------------------------------------------------
    // 表第 3 行：sending（我正忙着收，别再来一个）
    //   置 1：看见下降沿，而且当前没在收
    //   清 0：两个条件
    //         a. 第 10 次采样完成（停止位采完）
    //         b. 半位验真失败（起始位中点采到 1 → 是毛刺，放弃）
    //------------------------------------------------------------------
    reg sending;

    //------------------------------------------------------------------
    // 表第 4 行：baud_cnt（这一位数到第几拍了）
    //   复位 0；没在收就归零；数到 5207 归零；其它时候 +1
    //   ★ 采样点不在这里定义，在这里“被比较”
    //------------------------------------------------------------------
    reg [BW-1:0] baud_cnt;

    //------------------------------------------------------------------
    // 表第 5 行：bit_cnt（收到第几次采样了）
    //   0 = 起始位，1~8 = 数据位，9 = 停止位
    //   ★ 它每“采样一次”才 +1，不是每拍 +1
    //------------------------------------------------------------------
    reg [3:0] bit_cnt;

    //------------------------------------------------------------------
    // 表第 6 行：rx_shift（把 8 个数据位一位一位装进来）
    //------------------------------------------------------------------
    reg [7:0] rx_shift;

    //------------------------------------------------------------------
    // 采样时刻：正在收 + 计数器正好到半位
    //   注意它是一根 wire（组合），不是寄存器
    //------------------------------------------------------------------
    wire sample_en = sending && (baud_cnt == HALF_BAUD);

    //=========================================================================
    //  从这一行往下，就是每个“必须被记住的东西”各占一个 always 块
    //=========================================================================

    // ------------------------------------------------------------------
    // 块 A —— sending
    // ------------------------------------------------------------------
    always @(posedge Clk or negedge Rst_n) begin
        if (!Rst_n)
            sending <= 1'b0;
        else if (rx_nedge && !sending)
            sending <= 1'b1;                       // 看见下降沿，开工
        else if (sample_en && bit_cnt == 4'd9)
            sending <= 1'b0;                       // a. 收完了
        else if (sample_en && bit_cnt == 4'd0 && uart_rx_d1)
            sending <= 1'b0;                       // b. 毛刺，放弃
    end

    // ------------------------------------------------------------------
    // 块 B —— baud_cnt
    // ------------------------------------------------------------------
    always @(posedge Clk or negedge Rst_n) begin
        if (!Rst_n)
            baud_cnt <= {BW{1'b0}};
        else if (!sending)
            baud_cnt <= {BW{1'b0}};
        else if (baud_cnt == MCNT_BAUD)
            baud_cnt <= {BW{1'b0}};
        else
            baud_cnt <= baud_cnt + 1'b1;
    end

    // ------------------------------------------------------------------
    // 块 C —— bit_cnt（只在采样那一拍动）
    // ------------------------------------------------------------------
    always @(posedge Clk or negedge Rst_n) begin
        if (!Rst_n)
            bit_cnt <= 4'd0;
        else if (!sending)
            bit_cnt <= 4'd0;
        else if (sample_en) begin
            if (bit_cnt == 4'd9)
                bit_cnt <= 4'd0;
            else
                bit_cnt <= bit_cnt + 1'b1;
        end
    end

    // ------------------------------------------------------------------
    // 块 D —— rx_shift（只在收到数据位时动，往右移，新位进最高位）
    // ------------------------------------------------------------------
    always @(posedge Clk or negedge Rst_n) begin
        if (!Rst_n)
            rx_shift <= 8'd0;
        else if (sample_en && bit_cnt >= 4'd1 && bit_cnt <= 4'd8)
            rx_shift <= {uart_rx_d1, rx_shift[7:1]};
    end

    // ------------------------------------------------------------------
    // 块 E —— 对外交代
    //   Data   ：在停止位那一拍，把 rx_shift 整个搬过来
    //   Rx_Done：只在那一拍照 1 拍，下一拍自动回 0
    // ------------------------------------------------------------------
    always @(posedge Clk or negedge Rst_n) begin
        if (!Rst_n) begin
            Data    <= 8'd0;
            Rx_Done <= 1'b0;
        end
        else begin
            Rx_Done <= (sample_en && bit_cnt == 4'd9);   // 单拍
            if (sample_en && bit_cnt == 4'd9)
                Data <= rx_shift;
        end
    end

endmodule
