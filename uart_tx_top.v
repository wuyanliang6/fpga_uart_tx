//=============================================================================
// 文件名 : uart_tx_top.v
// 功能   : UART 发送模块的"上板顶层" —— 给 uart_tx 喂数据、把内部状态引到 LED
// 说明   : 这个文件只做三件事，和 uart_tx.v 是"外壳 + 内核"的关系：
//          1) 每 1 秒产生一个 send_tick，让 uart_tx 发一个字节
//          2) 每发完一帧，换下一个字节（55 → A5 → 0F → F0 → 循环）
//          3) 把几个内部信号引到 LED，让你不接示波器也能看见它在干活
//=============================================================================
`timescale 1ns/1ns

module uart_tx_top(
    input  wire       Clk,        // 板载 50MHz 晶振（Y18）
    input  wire       Rst_n,      // 板载复位按键 S4（B21），按下为 0
    output wire       Uart_Tx,    // 串口发送脚（M15），接 USB 转串口
    output wire [3:0] Led         // LED0~LED3
);

    //-------------------------------------------------------------------------
    // 1. 参数：这两个数决定"多久发一次"和"发多快"
    //-------------------------------------------------------------------------
    localparam CLOCK_FREQ = 50_000_000;      // 板载晶振 50MHz
    localparam BAUD       = 9600;            // 串口助手也要设 9600
    localparam TICK_MAX   = CLOCK_FREQ - 1;  // 数满 50,000,000 拍 = 1 秒

    //-------------------------------------------------------------------------
    // 1.5 先声明 uart_tx 的应答线（必须先声明后使用，否则 Vivado 会报重复声明）
    //-------------------------------------------------------------------------
    wire Tx_Done;

    //-------------------------------------------------------------------------
    // 2. 1 秒的节拍：send_tick 只宽 1 拍（20ns），是"请求发送"的握手信号
    //-------------------------------------------------------------------------
    reg [25:0] tick_cnt;      // 2^26 = 67,108,864 > 50,000,000，够数
    reg        send_tick;

    always @(posedge Clk or negedge Rst_n) begin
        if (!Rst_n) begin
            tick_cnt  <= 26'd0;
            send_tick <= 1'b0;
        end
        else if (tick_cnt == TICK_MAX) begin
            tick_cnt  <= 26'd0;
            send_tick <= 1'b1;               // 只在这一拍为 1
        end
        else begin
            tick_cnt  <= tick_cnt + 1'b1;
            send_tick <= 1'b0;
        end
    end

    //-------------------------------------------------------------------------
    // 3. 数据表：每发完一帧，索引 +1，四选一
    //    这四个字节是故意选的，下面第 9 讲"验证"会说为什么：
    //    55 = 0101_0101（方波感强）、A5 = 1010_0101（交替）、
    //    0F = 0000_1111（低 4 位为 1）、F0 = 1111_0000（高 4 位为 1）
    //-------------------------------------------------------------------------
    reg [1:0] idx;

    always @(posedge Clk or negedge Rst_n) begin
        if (!Rst_n)
            idx <= 2'd0;
        else if (Tx_Done)                    // 发完一帧才换，保证一帧内数据不变
            idx <= idx + 1'b1;
    end

    reg [7:0] send_data;

    always @(*) begin
        case (idx)
            2'd0:    send_data = 8'h55;
            2'd1:    send_data = 8'hA5;
            2'd2:    send_data = 8'h0F;
            default: send_data = 8'hF0;
        endcase
    end

    //-------------------------------------------------------------------------
    // 4. 例化核心模块（uart_tx.v）
    //    注意：这里没有写 defparam，用的是"参数列表"写法 #(...)
    //-------------------------------------------------------------------------
    uart_tx #(
        .CLOCK_FREQ (CLOCK_FREQ),
        .BAUD       (BAUD)
    ) u_uart_tx (
        .Clk     (Clk),
        .Rst_n   (Rst_n),
        .Send_Go (send_tick),
        .Data    (send_data),
        .Uart_Tx (Uart_Tx),
        .Tx_Done (Tx_Done)
    );

    //-------------------------------------------------------------------------
    // 5. 心跳：每发完一帧翻转一次 → 约 0.5Hz 的闪（一帧 1.04ms + 等 1 秒）
    //-------------------------------------------------------------------------
    reg heartbeat;

    always @(posedge Clk or negedge Rst_n) begin
        if (!Rst_n)
            heartbeat <= 1'b0;
        else if (Tx_Done)
            heartbeat <= ~heartbeat;
    end

    //-------------------------------------------------------------------------
    // 6. 把内部状态引到 LED（不接仪器也能看见）
    //
    //    Led[0] : 每发一帧翻转一次     → 慢闪，证明"在发"
    //    Led[1] : 直接接 Uart_Tx 线    → 串口空闲是高，发送时会快速闪动
    //    Led[3:2] : 当前发的是第几个字节（00/01/10/11）
    //-------------------------------------------------------------------------
    assign Led[0]   = heartbeat;
    assign Led[1]   = Uart_Tx;
    assign Led[3:2] = idx;
    // 注：如果发现 LED 亮灭和这里说的相反，说明板子 LED 是低电平点亮，
    //     把上面三条各自取反（加一个 ~ ）即可，见手册第 9 步。

endmodule
