//=============================================================================
//  uart_rx_top.v  ——  串口回环：电脑发一个字节，板子收下来，再发回去
//
//  作用：这是 UART 收发两个模块的“串起来”。
//        串口助手发 0x55，你会看到它自己回一个 0x55。
//
//  连线：板子上的 USB 线已经同时接了 JTAG 和串口，不需要额外接线。
//=============================================================================
module uart_rx_top #(
    parameter CLOCK_FREQ = 50_000_000,
    parameter BAUD       = 9600
)(
    input               Clk,        // Y18  50 MHz
    input               Rst_n,      // B21  S4 按键，按下复位
    input               Uart_Rx,    // J21  ← 电脑发过来
    output              Uart_Tx,    // M15  → 发回电脑
    output reg  [3:0]   Led         // M22/N22/L21/K21
);

    //------------------------------------------------------------------
    // 接收到的字节 + “收完”的单拍脉冲
    //------------------------------------------------------------------
    wire [7:0] rx_data;
    wire       rx_done;

    //------------------------------------------------------------------
    // 要发出去的字节 + “开始发”的单拍脉冲
    //------------------------------------------------------------------
    reg  [7:0] tx_data;
    reg        tx_go;
    wire       tx_done;

    //------------------------------------------------------------------
    // 接收模块
    //------------------------------------------------------------------
    uart_rx #(
        .CLOCK_FREQ (CLOCK_FREQ),
        .BAUD       (BAUD)
    ) u_uart_rx (
        .Clk        (Clk),
        .Rst_n      (Rst_n),
        .uart_rx    (Uart_Rx),
        .Data       (rx_data),
        .Rx_Done    (rx_done)
    );

    //------------------------------------------------------------------
    // 发送模块
    //------------------------------------------------------------------
    uart_tx #(
        .CLOCK_FREQ (CLOCK_FREQ),
        .BAUD       (BAUD)
    ) u_uart_tx (
        .Clk        (Clk),
        .Rst_n      (Rst_n),
        .Send_Go    (tx_go),
        .Data       (tx_data),
        .Uart_Tx    (Uart_Tx),
        .Tx_Done    (tx_done)
    );

    //------------------------------------------------------------------
    // 搬运：收到一个字节 → 下一拍请求发送
    //
    //   注意 send_go 只给一拍（用 rx_done 打一拍），
    //   因为发送模块的规矩是“单拍请求”。
    //------------------------------------------------------------------
    always @(posedge Clk or negedge Rst_n) begin
        if (!Rst_n) begin
            tx_data <= 8'd0;
            tx_go   <= 1'b0;
            Led     <= 4'd0;
        end
        else begin
            tx_go <= rx_done;              // 单拍脉冲，转一手给发送端

            if (rx_done) begin
                tx_data <= rx_data;        // 锁存收到的字节
                Led     <= Led + 1'b1;     // 收到一个，灯变一次
            end
        end
    end

endmodule
